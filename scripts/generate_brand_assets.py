#!/usr/bin/env python3
"""Generate code-native assets from the maintainer-provided Carbon C design."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# Coordinates follow the supplied square logo; the foreground fits adaptive masks.
MARK = (
    "M443,282 H814 L944,494 H811 L750,395 H507 L370,627 "
    "L507,858 H751 L815,759 H946 L814,970 H443 L239,627 Z "
    "M495,523 H759 V589 H495 Z M495,664 H759 V729 H495 Z"
)
ACCENT = "#00FF88"
BACKGROUND = "#0B0F0D"


def svg(viewbox: str, *, background: bool = False) -> str:
    backdrop = (
        f'<path fill="{BACKGROUND}" d="M0 0h1254v1254H0z"/>' if background else ""
    )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{viewbox}">\n'
        f'  {backdrop}\n  <path fill="{ACCENT}" d="{MARK}"/>\n</svg>\n'
    )


def vector(viewport: int, path: str, color: str) -> str:
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by scripts/generate_brand_assets.py. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp" android:height="108dp"\n'
        f'    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">\n'
        f'    <path android:fillColor="{color}" android:pathData="{path}" />\n'
        "</vector>\n"
    )


def main() -> None:
    assets = ROOT / "assets/branding"
    public = ROOT / "frontend/public"
    drawables = ROOT / "android/app/src/main/res/drawable"
    for directory in (assets, public, drawables):
        directory.mkdir(parents=True, exist_ok=True)
    (assets / "carbonpanel-logo.svg").write_text(svg("0 0 1254 1254", background=True))
    mark = svg("220 250 760 760")
    (assets / "carbonpanel-mark.svg").write_text(mark)
    (public / "carbonpanel-mark.svg").write_text(mark)
    (public / "favicon.svg").write_text(svg("190 200 850 850", background=True))
    (drawables / "ic_launcher_foreground.xml").write_text(vector(1254, MARK, ACCENT))
    (drawables / "ic_launcher_monochrome.xml").write_text(vector(1254, MARK, "#FFFFFF"))
    # A tight viewport gives in-app branding the same visual weight as text.
    # Translate the launcher geometry to a zero-based square viewport.
    (drawables / "carbonpanel_mark.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by scripts/generate_brand_assets.py. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="32dp" android:height="32dp"\n'
        '    android:viewportWidth="760" android:viewportHeight="760">\n'
        '    <group android:translateX="-220" android:translateY="-250">\n'
        f'        <path android:fillColor="{ACCENT}" android:pathData="{MARK}" />\n'
        "    </group>\n</vector>\n"
    )


if __name__ == "__main__":
    main()
